import { test, expect } from '@playwright/test'
import { immortal, opera } from './fixtures'

test('Instant доступен сразу, пауза и смена режима сохраняют позиции', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'PGN', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст PGN' }).fill(opera)
  await page.getByRole('button', { name: 'Импортировать PGN' }).click()
  await page.getByRole('button', { name: /Morphy – Duke/ }).click()
  await page.getByRole('combobox', { name: 'Тип разбора' }).selectOption('deep-review')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Начать анализ' }).click()
  await expect(page.getByText('Предварительный проход завершён')).toBeVisible({ timeout: 20_000 })
  await expect(page.getByRole('heading', { name: /График партии · предварительный/ })).toBeVisible()
  await page.getByRole('button', { name: 'К последнему готовому ходу' }).click()
  await expect(page.locator('.board-context')).toContainText('Rd8#')
  await page.getByRole('button', { name: 'Пауза', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Продолжить' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Предварительный проход завершён')).toBeVisible()
  await page.getByRole('combobox', { name: 'Тип разбора' }).selectOption('smart')
  await page.getByRole('button', { name: 'Начать анализ' }).click()
  await expect(page.getByRole('heading', { name: /Итоги партии/ })).toBeVisible({ timeout: 90_000 })
  await expect(page.getByText('Предварительный проход завершён')).toHaveCount(0)
  await expect(page.getByText('Анализ завершён')).toBeVisible()
})

test('автоматический предварительный анализ ограничен выбранным числом партий', async ({ page }) => {
  await page.goto('/#settings')
  await page.getByLabel('Предварительный анализ последних партий').selectOption('1')
  await page.goto('/#home')
  await page.getByRole('button', { name: 'PGN', exact: true }).click()
  await page.getByRole('textbox', { name: 'Текст PGN' }).fill(opera + '\n\n' + immortal)
  await page.getByRole('button', { name: 'Импортировать PGN' }).click()
  await expect(page.getByRole('button', { name: /Morphy.*Предварительный разбор/ })).toBeVisible({ timeout: 20_000 })
  await expect(page.getByRole('button', { name: /Anderssen.*Без анализа/ })).toBeVisible()
  await page.getByRole('button', { name: /Morphy.*Предварительный разбор/ }).click()
  await expect(page.getByText('Предварительный проход завершён')).toBeVisible()
  await expect(page.getByRole('heading', { name: /Итоги партии/ })).toHaveCount(0)
})
